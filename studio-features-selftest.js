'use strict';
const assert=require('assert');
const Core=require('./studio-features-core.js');
const drill={id:'d1',name:'Round trip',description:'test',tags:['x'],robotPoseReference:'base_back',robotPose:{x:0,y:0,yawDeg:0},startNodeId:'s1',settings:{repetitions:3,delayBetweenSets:1},nodes:[{id:'s1',type:'shot',label:'Ball',x:300,y:260,params:{speedMps:6,spinRps:10,elevationDeg:10,aimDeg:0}}],edges:[]};
const portable=Core.makePortableDrill(drill,{createdAt:'2026-08-30T00:00:00Z'});
assert(Core.validatePortableDrill(portable).valid);
const serve=Core.makePortableDrill({...drill,startNodeId:'v1',nodes:[{id:'v1',type:'serve',label:'Serve',x:300,y:260,params:{speedMps:5,spinRps:-8,elevationDeg:-16,aimDeg:0}}]});
assert(Core.validatePortableDrill(serve).valid);
assert.strictEqual(Core.deserializePortableDrill(Core.serializePortableDrill(serve)).drill.nodes[0].type,'serve');
const serveAiRequest=Core.buildExternalAiRequest({userRequest:'make a serve drill'});
assert(serveAiRequest.includes('"type":"serve"'));
assert(serveAiRequest.includes('"elevationDeg":-16'));
const helpRequest=Core.buildExternalAiRequest({userRequest:'How do I calibrate?',requestKind:'help',appContext:{screen:'Robot',activeDrill:null,drillSource:null,selection:null,localContext:['Open section: Guided launch calibration'],secret:'do not include'}});
assert(helpRequest.includes('TASK MODE: APP HELP'));
assert(helpRequest.includes('"screen": "Robot"'));
assert(helpRequest.includes('Open section: Guided launch calibration'));
assert(helpRequest.includes('APP CAPABILITIES'));
assert(helpRequest.includes('Idle STOP leaves BLE connected'));
assert(!helpRequest.includes('do not include'));
assert(helpRequest.includes('Bluetooth logs'));
const libraryCreateRequest=Core.buildExternalAiRequest({userRequest:'Make a two-point drill',appContext:{screen:'Drill library',activeDrill:null,localContext:['Browsing: Built-in drills','Folder: Built-in / Match play']}});
assert(libraryCreateRequest.includes('TASK MODE: CREATE'));
assert(libraryCreateRequest.includes('Folder: Built-in / Match play'));
assert(!libraryCreateRequest.includes('CURRENT DRILL WHEN EDITING:\n{'));
const varied=Core.makePortableDrill({...drill,nodes:[{...drill.nodes[0],variation:{enabled:true,placement:{depthCm:15,lateralCm:20},clearance:{minCm:8,maxCm:12},speed:{minMps:5.4,maxMps:6.8},spin:{minRps:4,maxRps:16}}}]});
assert(Core.validatePortableDrill(varied).valid);
const invalidVariation=JSON.parse(JSON.stringify(varied));invalidVariation.drill.nodes[0].variation.speed={minMps:9,maxMps:4};
assert(!Core.validatePortableDrill(invalidVariation).valid);
const encoded=Core.serializePortableDrill(portable);
assert.deepStrictEqual(Core.deserializePortableDrill(encoded).drill.nodes,drill.nodes);
const url=Core.makeShareUrl(portable,'https://example.com/app?x=1#old');
assert.deepStrictEqual(Core.parseShareHash(url.slice(url.indexOf('#'))).drill.nodes,drill.nodes);
assert.throws(()=>Core.deserializePortableDrill('not-json'));
assert(!Core.validatePortableDrill({}).valid);
const prose=`Sure.\n\nTABLE_TENNIS_ROBOT_STUDIO_DRILL_BEGIN\n${JSON.stringify(portable)}\nTABLE_TENNIS_ROBOT_STUDIO_DRILL_END\nDone.`;
assert.strictEqual(Core.parseExternalAiResult(prose).name,'Round trip');
console.log('PASS sharing/AI/serve feature logic');
